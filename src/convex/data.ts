/** إحداثيات نهائية للحرفي: الدقيقة إن وُجدت، وإلا مركز ولايته */
export function resolveCoords(
  wilayaName: string,
  lat?: number | null,
  lng?: number | null,
): [number, number] {
  if (typeof lat === "number" && typeof lng === "number") return [lat, lng];
  return wilayaCoords(wilayaName);
}

